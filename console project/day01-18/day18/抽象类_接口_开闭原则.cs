namespace day18
{
    internal class 抽象类_接口_开闭原则
    {
        //普通类: 对抽象出来的行为与属性进行封装
        //通过类的派生与继承 : 对类进行横向与纵向的扩展  

        //抽象类: 函数成员没有完全实现的类  
        //作用 1. 作为基类来被继承
        //     2. 声明变量 用基类类型的变量去引用一个子类类型的实例,子类已经实现了抽象类为实现的方法 : 里氏转换:向上转型

        //开闭原则: 不是修bug ,或添加新功能 ,不能去修改一个类的代码,特别是函数成员代码  对修改关闭，对扩展开放

        //我们应该封装 不变的 稳定的 固定的 确定的 成员
        //而把那些 不确定的 有坑呢改变的代码 声明成为抽象成员, 并留给子类去实现

    }
    abstract class Student
    {
        abstract public void Study();
    }
